-- PMV2: referencia del anclaje de integridad de un evento.
-- Solo crea una tabla nueva. No altera eventos, variables ni tablas del PMV1.
-- Guarda hash, red, identificador de transacción y fecha. No guarda nombre,
-- documento ni otros datos del productor.
-- Puede ejecutarse de nuevo. RLS activo y sin políticas, igual que el resto.
-- Si se elimina el evento, la fila permanece con evento_id nulo: es el eslabón
-- ya escrito de la cadena de prueba y no se reescribe.

CREATE TABLE IF NOT EXISTS referencias_anclaje (
  id UUID PRIMARY KEY,
  evento_id UUID,
  hash_evento VARCHAR(64) NOT NULL,
  red VARCHAR(40) NOT NULL,
  identificador_transaccion VARCHAR(64) NOT NULL,
  fecha TIMESTAMPTZ NOT NULL,
  secuencia BIGINT GENERATED BY DEFAULT AS IDENTITY,
  CONSTRAINT uq_referencias_anclaje_evento UNIQUE (evento_id),
  CONSTRAINT uq_referencias_anclaje_secuencia UNIQUE (secuencia),
  CONSTRAINT fk_referencias_anclaje_evento
    FOREIGN KEY (evento_id) REFERENCES eventos_trazabilidad (id) ON DELETE SET NULL,
  CONSTRAINT ck_referencias_anclaje_hash CHECK (hash_evento ~ '^[0-9a-f]{64}$'),
  CONSTRAINT ck_referencias_anclaje_identificador CHECK (identificador_transaccion ~ '^[0-9a-f]{64}$'),
  CONSTRAINT ck_referencias_anclaje_red CHECK (char_length(red) >= 1)
);

CREATE INDEX IF NOT EXISTS idx_referencias_anclaje_secuencia ON referencias_anclaje (secuencia);

ALTER TABLE referencias_anclaje ENABLE ROW LEVEL SECURITY;
